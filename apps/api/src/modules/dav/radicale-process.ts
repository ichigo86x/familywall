import { spawn, type ChildProcess } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Logger } from "@nestjs/common";
import { splitCommand } from "../../config/command-line";

/** Radicale user that owns the family lists; every Familywall member is mapped to it. */
export const DAV_FAMILY_USER = "famiglia";

const RESTART_DELAY_MS = 5_000;

/**
 * Runs Radicale as a child process bound to localhost. It trusts the
 * X-Remote-User header, so it must only ever be reachable through the
 * Familywall gateway, which authenticates members first.
 */
export class RadicaleProcess {
  private readonly logger = new Logger("Radicale");
  private child: ChildProcess | null = null;
  private stopping = false;
  private failures = 0;

  public constructor(
    private readonly command: string,
    private readonly port: number,
    private readonly dataDir: string
  ) {}

  public get baseUrl(): string {
    return `http://127.0.0.1:${this.port}`;
  }

  public get enabled(): boolean {
    return this.command.trim() !== "";
  }

  public start(): void {
    if (!this.enabled) {
      this.logger.log("CalDAV server disabled (RADICALE_COMMAND is empty).");
      return;
    }
    const configPath = this.writeConfig();
    const [executable, ...args] = splitCommand(this.command);
    this.stopping = false;

    const child = spawn(executable!, [...args, "--config", configPath], { stdio: ["ignore", "pipe", "pipe"], windowsHide: true });
    this.child = child;
    child.stdout?.on("data", (chunk: Buffer) => this.logger.debug(chunk.toString().trim()));
    let missingModule = false;
    child.stderr?.on("data", (chunk: Buffer) => {
      const line = chunk.toString().trim();
      if (/No module named .?radicale/.test(line)) {
        missingModule = true;
        return;
      }
      if (/error|critical|traceback/i.test(line)) {
        this.logger.warn(line.slice(0, 500));
      }
    });
    child.on("error", (error) => {
      this.logger.warn(`CalDAV server not started (${error.message}). In development run "npm run python:setup", or set RADICALE_COMMAND.`);
    });
    child.on("exit", (code) => {
      this.child = null;
      if (this.stopping) {
        return;
      }
      if (missingModule) {
        // Retrying cannot help: Radicale is not installed for this Python.
        this.logger.error(
          `Radicale is not installed for ${executable}: calendars, lists, notes and shifts are unavailable. ` +
            (process.env.RADICALE_COMMAND
              ? `RADICALE_COMMAND is set to "${process.env.RADICALE_COMMAND}": remove it from this terminal (PowerShell: Remove-Item Env:RADICALE_COMMAND) to use the venv of "npm run python:setup", then restart the API.`
              : "In development run \"npm run python:setup\" and restart the API, or set RADICALE_COMMAND.")
        );
        return;
      }
      this.failures += 1;
      if (this.failures > 5) {
        this.logger.error(`CalDAV server keeps exiting (code ${code}); giving up until restart.`);
        return;
      }
      this.logger.warn(`CalDAV server exited (code ${code}); restarting in ${RESTART_DELAY_MS / 1000}s.`);
      setTimeout(() => this.start(), RESTART_DELAY_MS).unref();
    });
    this.logger.log(`CalDAV server starting on ${this.baseUrl}`);
  }

  public stop(): void {
    this.stopping = true;
    this.child?.kill();
    this.child = null;
  }

  private writeConfig(): string {
    const root = path.join(this.dataDir, "radicale");
    const collections = path.join(root, "collections");
    mkdirSync(collections, { recursive: true });
    const configPath = path.join(root, "config");
    const ini = [
      "# Generated by Familywall at every start: edits are overwritten.",
      "[server]",
      `hosts = 127.0.0.1:${this.port}`,
      "",
      "[auth]",
      "# The Familywall gateway authenticates members and sends X-Remote-User.",
      "type = http_x_remote_user",
      "",
      "[rights]",
      "type = owner_only",
      "",
      "[storage]",
      `filesystem_folder = ${collections.replace(/\\/g, "/")}`,
      "",
      "[web]",
      "type = none",
      "",
      "[logging]",
      "level = warning",
      ""
    ].join("\n");
    writeFileSync(configPath, ini);
    return configPath;
  }
}
